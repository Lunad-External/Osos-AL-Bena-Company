// Static production build for Apache hosting (e.g. GoDaddy cPanel Web Hosting,
// which has no Node.js). Every page is rendered to full HTML with the same
// renderer the Node server uses, and an .htaccess file reproduces the
// server's redirects, 404/410 pages, caching and security headers.
// Run `npm run build` first, then `npm run build:static`; upload dist-static/.
import { cp, mkdir, readFile, rm, writeFile, stat, readdir } from "node:fs/promises";
import { readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import {
  render,
  publicRoutes,
  robotsTxt,
  sitemapXml,
  DEFAULT_ORIGIN,
} from "../src/entry-server";
import { movedPaths, removedPaths } from "../src/seo";

const out = "dist-static";
const origin = (process.env.SITE_URL || DEFAULT_ORIGIN).replace(/\/$/, "");
const host = new URL(origin).host;
const lastmod = new Date().toISOString().slice(0, 10);

await rm(out, { recursive: true, force: true });
await cp("dist", out, {
  recursive: true,
  filter: (src) => !src.includes("/.vite") && !src.endsWith("dist/index.html"),
});

// Inline the stylesheet, as the Node server does.
const template = (await readFile("dist/index.html", "utf8")).replace(
  /<link rel="stylesheet"[^>]*href="\/(assets\/[^"]+\.css)"[^>]*>/,
  (_tag, file) => `<style>${readFileSync(`dist/${file}`, "utf8")}</style>`,
);

const write = async (file: string, html: string) => {
  await mkdir(file.substring(0, file.lastIndexOf("/")), { recursive: true });
  await writeFile(file, html);
};
for (const path of publicRoutes) {
  const { status, html } = render(path, template, { origin });
  if (status !== 200) throw Error(`${path} rendered ${status}`);
  await write(`${out}${path}index.html`, html);
}
await write(`${out}/404.html`, render("/404/", template, { origin }).html);
await write(
  `${out}/410.html`,
  render([...removedPaths][0], template, { origin }).html,
);
await writeFile(`${out}/robots.txt`, robotsTxt(origin));
await writeFile(`${out}/sitemap.xml`, sitemapXml(origin, lastmod));

// Leave out images no page references (old uploads kept in the repo).
const pages = (await Promise.all(
  [...publicRoutes.map((p) => `${out}${p}index.html`), `${out}/404.html`].map((f) => readFile(f, "utf8")),
)).join("");
const bundles = (await Promise.all(
  (await readdir(`${out}/assets`)).map((f) => readFile(`${out}/assets/${f}`, "utf8")),
)).join("");
for (const f of await readdir(`${out}/images`)) {
  const base = f.replace(/-480(\.\w+)$/, "$1");
  if (![pages, bundles].some((c) => c.includes(`images/${f}`) || c.includes(`images/${base}`)))
    await rm(`${out}/images/${f}`);
}

// --- .htaccess ---------------------------------------------------------
const esc = (s: string) => s.replace(/[.+*?^$()[\]{}|\\]/g, "\\$&");
const strip = (p: string) => p.replace(/^\/|\/$/g, "");
const hostRe = esc(host);
const lines: string[] = [
  "# Generated by scripts/build-static.tsx. Do not edit by hand.",
  "Options -Indexes -MultiViews",
  "DirectoryIndex index.html",
  "DirectorySlash Off",
  "ErrorDocument 404 /404.html",
  "ErrorDocument 410 /410.html",
  "AddType application/manifest+json .webmanifest",
  "AddType image/webp .webp",
  "AddType image/avif .avif",
  "AddDefaultCharset utf-8",
  "",
  "RewriteEngine On",
  "",
  "# www and plain HTTP go to the preferred origin in one hop.",
  `RewriteCond %{HTTP_HOST} ^www\\.${hostRe}$ [NC]`,
  `RewriteRule ^(.*)$ ${origin}/$1 [R=301,L]`,
  "RewriteCond %{HTTPS} !=on",
  "RewriteCond %{HTTP:X-Forwarded-Proto} !=https",
  `RewriteCond %{HTTP_HOST} ^${hostRe}$ [NC]`,
  `RewriteRule ^(.*)$ ${origin}/$1 [R=301,L]`,
  "",
  "# /index.html and /folder/index.html are served at /folder/.",
  "RewriteCond %{THE_REQUEST} \\s/+((?:[^\\s?]*/)?)index\\.html[\\s?]",
  "RewriteRule ^ /%1 [R=301,L]",
  "",
  "# Renamed product URLs.",
  ...Object.entries(movedPaths).map(
    ([from, to]) => `RewriteRule ^${esc(strip(from))}/?$ ${to} [NC,R=301,L]`,
  ),
  "",
  "# Withdrawn products: 410 Gone.",
  `RewriteRule ^(?:${[...removedPaths].map((p) => esc(strip(p))).join("|")})/?$ - [NC,G,L]`,
  "",
  "# Every page has one lowercase URL with a trailing slash.",
  ...publicRoutes
    .filter((p) => p !== "/")
    .flatMap((p) => [
      `RewriteCond %{REQUEST_URI} !^${esc(p)}$`,
      `RewriteRule ^${esc(strip(p))}/?$ ${p} [NC,R=301,L]`,
    ]),
  "",
  "# Any other folder without a trailing slash.",
  "RewriteCond %{REQUEST_FILENAME} -d",
  "RewriteRule ^(.+[^/])$ /$1/ [R=301,L]",
  "",
  "<IfModule mod_headers.c>",
  '  Header always set X-Content-Type-Options "nosniff"',
  '  Header always set Referrer-Policy "strict-origin-when-cross-origin"',
  '  Header always set X-Frame-Options "SAMEORIGIN"',
  '  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=()"',
  `  Header always set Strict-Transport-Security "max-age=31536000; includeSubDomains" "expr=%{HTTPS} == 'on' && %{HTTP_HOST} == '${host}'"`,
  '  <FilesMatch "\\.html$">',
  '    Header set Cache-Control "public, max-age=0, must-revalidate"',
  "  </FilesMatch>",
  '  <FilesMatch "\\.(webp|avif|png|jpe?g|svg|ico)$">',
  '    Header set Cache-Control "public, max-age=2592000"',
  "  </FilesMatch>",
  '  <FilesMatch "\\.pdf$">',
  '    Header set Cache-Control "public, max-age=86400"',
  "  </FilesMatch>",
  '  <FilesMatch "\\.(txt|xml|webmanifest)$">',
  '    Header set Cache-Control "public, max-age=3600"',
  "  </FilesMatch>",
  '  <If "%{REQUEST_URI} =~ m#^/assets/#">',
  '    Header set Cache-Control "public, max-age=31536000, immutable"',
  "  </If>",
  "</IfModule>",
  "",
  "<IfModule mod_deflate.c>",
  "  AddOutputFilterByType DEFLATE text/html text/plain text/css text/xml application/xml application/javascript text/javascript application/json application/manifest+json image/svg+xml",
  "</IfModule>",
  "",
];
await writeFile(`${out}/.htaccess`, lines.join("\n"));

const zip = "obc-website-static.zip";
await rm(zip, { force: true });
execFileSync("zip", ["-qr", `../${zip}`, "."], { cwd: out });
console.log(
  `${out}/ ready: ${publicRoutes.length} pages, 404/410 pages, robots.txt, sitemap.xml, .htaccess; ${zip} ${((await stat(zip)).size / 1e6).toFixed(1)} MB`,
);
